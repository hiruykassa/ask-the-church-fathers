export const searchFathers = (query) => {
  if (!query.trim()) return [];
  const q = query.toLowerCase();

  const results = [];

  for (const father of fathers) {
    const nameMatch = father.name.toLowerCase().includes(q);
    const topicMatch = father.topics.some(t => t.includes(q));
    const workMatch = father.works.some(
      w => w.title.toLowerCase().includes(q) || w.excerpt.toLowerCase().includes(q)
    );

    if (nameMatch || topicMatch || workMatch) {
      // Collect matching works (or all if name matched)
      const matchingWorks = nameMatch
        ? father.works
        : father.works.filter(
            w => w.title.toLowerCase().includes(q) || w.excerpt.toLowerCase().includes(q)
              || father.topics.some(t => t.includes(q))
          );

      results.push({
        father,
        works: matchingWorks.length > 0 ? matchingWorks : father.works.slice(0, 2),
      });
    }
  }

  return results;
};
